#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Build detection and strict-FPR tables from per-panel result files."""
from __future__ import annotations
import glob, json, collections, statistics as st
from pathlib import Path

OUT = Path("tables_v2"); OUT.mkdir(exist_ok=True)

# canonical display order / names
ORDER = ["GLASS", "Fast-DetectGPT", "Binoculars", "log-perplexity",
         "log-rank", "RoBERTa-OpenAI", "DetectGPT", "DNA-GPT", "Ghostbuster"]


def short(name):
    for k in ORDER:
        if name.lower().startswith(k.lower().split()[0].lower()) or k.lower() in name.lower():
            return k
    return name.split(" (")[0]


def collect():
    A = collections.defaultdict(dict); T = collections.defaultdict(dict)
    for patt in ("results_v2/competitors_en_s*.json", "results_v2/tier2_en_s*.json"):
        for f in sorted(glob.glob(patt)):
            s = int(f.split("_s")[-1].split(".")[0])
            for r in json.load(open(f)):
                d = short(r["detector"])
                A[d][s] = r["auc"]; T[d][s] = r["tpr_at_1"]
    return A, T


def ms(vals):
    v = [x for x in vals if x is not None]
    if not v: return None, None
    return sum(v) / len(v), (st.pstdev(v) if len(v) > 1 else 0.0)


def order_dets(A):
    present = [d for d in ORDER if d in A] + [d for d in A if d not in ORDER]
    return sorted(present, key=lambda d: -(ms(A[d].values())[0] or 0))


def write_headline(A, T, panels):
    rows = order_dets(A)
    L = ["% RE-DO detection headline on the English v2_english panels.",
         "% Auto-generated by make_v2_tables.py from results_v2/*_en_s*.json.",
         "\\begin{table*}[t]\\centering\\small",
         "\\caption{Detection on five English, domain-stratified \\texttt{frontier} "
         "panels (200 prompts each, eight RAID domains, 18 instruction-tuned "
         "generators), \\texttt{v2\\_english} library. Per-detector AUC and "
         "TPR@1\\%FPR, mean$\\pm$std over the five panels; identical held-out test "
         "docs across detectors. \\textbf{Bold} = best.}",
         "\\label{tab:headline-v2}",
         "\\begin{tabular}{lcc}", "\\toprule",
         "Detector & AUC & TPR @ 1\\% FPR \\\\", "\\midrule"]
    bestA = max((ms(A[d].values())[0] or 0) for d in rows)
    bestT = max((ms(T[d].values())[0] or 0) for d in rows)
    for d in rows:
        am, asd = ms(A[d].values()); tm, tsd = ms(T[d].values())
        a = f"\\textbf{{{am:.3f}}}$\\pm${asd:.3f}" if abs(am - bestA) < 1e-9 else f"{am:.3f}$\\pm${asd:.3f}"
        t = f"\\textbf{{{tm:.3f}}}$\\pm${tsd:.3f}" if abs(tm - bestT) < 1e-9 else f"{tm:.3f}$\\pm${tsd:.3f}"
        name = "\\textbf{GLASS}" if d == "GLASS" else d
        L.append(f"{name} & {a} & {t} \\\\")
    L += ["\\bottomrule", "\\end{tabular}",
          f"\\caption*{{\\footnotesize Aggregated over {panels} panels.}}",
          "\\end{table*}"]
    (OUT / "tab_headline_v2.tex").write_text("\n".join(L) + "\n")


def write_strict(A, T, panels):
    rows = order_dets(A)
    L = ["% RE-DO strict-FPR table (English v2_english panels).",
         "\\begin{table}[t]\\centering\\small",
         "\\caption{TPR at 1\\% FPR on the five English stratified panels "
         "(\\texttt{v2\\_english}), mean$\\pm$std.}",
         "\\label{tab:strict-fpr-v2}",
         "\\begin{tabular}{lc}", "\\toprule",
         "Detector & TPR @ 1\\% FPR \\\\", "\\midrule"]
    best = max((ms(T[d].values())[0] or 0) for d in rows)
    for d in sorted(rows, key=lambda d: -(ms(T[d].values())[0] or 0)):
        tm, tsd = ms(T[d].values())
        cell = f"\\textbf{{{tm:.3f}}}$\\pm${tsd:.3f}" if abs(tm - best) < 1e-9 else f"{tm:.3f}$\\pm${tsd:.3f}"
        name = "\\textbf{GLASS}" if d == "GLASS" else d
        L.append(f"{name} & {cell} \\\\")
    L += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    (OUT / "tab_strict_fpr_v2.tex").write_text("\n".join(L) + "\n")


def main():
    A, T = collect()
    if not A:
        raise SystemExit("no results found under results_v2/*_en_s*.json")
    panels = len({s for d in A for s in A[d]})
    write_headline(A, T, panels)
    write_strict(A, T, panels)
    print(f"[ok] wrote {OUT}/tab_headline_v2.tex and tab_strict_fpr_v2.tex")
    print(f"     detectors: {order_dets(A)}  ({panels} panels)")

    print("\n=== RE-DO tables that still need their own English runs ===")
    print(" tab_symmetric_v2    : run OTB-supervised + PROFILER on the English panels")
    print(" tab_stress_profile  : RAID-English attack stages (decoding/DIPPER/edit)")
    print(" tab_thirdparty_v2   : product_eval.py --version v2_english on HC3/TB/MAGE")
    print(" ablations (K/encoder/calibration): sweep on the English panels")


if __name__ == "__main__":
    main()
